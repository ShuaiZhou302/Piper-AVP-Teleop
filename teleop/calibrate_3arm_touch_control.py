#!/usr/bin/env python3
"""
One-terminal 3-arm touch calibration.

Run all arms in command mode (mode=1, auto_enable=true). This script:
  1. controls one active arm at a time with keyboard Cartesian jogs,
  2. records MID/LEFT/RIGHT tip positions for each shared physical point,
  3. resets each arm after recording to reduce collision risk,
  4. fits LEFT->MID and RIGHT->MID rigid transforms with SVD.
"""
